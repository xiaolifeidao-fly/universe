/**
 * Galaxy 控制台的文案字典与 i18n Provider。用法和 web / manager 的 useLocale() 一致。
 *
 * 为什么这里没有用 @shared/i18n/createLocaleProvider：
 *
 * client/shared 没有自己的 node_modules，靠 client/shared/node_modules 这个**唯一的**
 * 符号链接解析裸导入，而它指向第一个安装的那个 app（manager）。于是 shared 里那个
 * `<ConfigProvider>` 来自 manager 的 antd 实例，本应用页面里的 `<Layout.Header>`
 * 来自自己那份 —— 两份实例就是两套 React context，主题 token 传不过去。
 * 症状很具体：命令条会退回 antd 默认的深海军蓝底，配上深色标题，一个字看不见。
 *
 * shared 里其余几个文件没有这个问题，继续用：managerTheme 是纯数据，
 * createAuthStore 只碰 localStorage，createHttpClient 只碰 axios ——
 * 它们都不渲染 antd 组件，也就不依赖 React context 的同一性。
 *
 * 根治办法是把 client/ 做成 npm workspaces，让三个 app 共用一份提升后的 antd；
 * 那之后这个文件可以换回 @shared 的工厂。
 *
 * 只开中英两种（和 manager 一致）。加页面时两个语言都要补 key —— 这是硬约束，
 * 缺一个 key 在另一种语言下就会露出裸键名。
 */

